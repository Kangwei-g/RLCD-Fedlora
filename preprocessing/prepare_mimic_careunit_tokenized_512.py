import argparse
import json
import pickle
from pathlib import Path

from datasets import Dataset
from transformers import RobertaTokenizer, GPT2Tokenizer


MODEL_FILE = 'FacebookAI/roberta-base'


def parse_args():
    parser = argparse.ArgumentParser(
        description="Pre-tokenize federated mimic_careunit splits for repeated DQN/FL runs."
    )
    parser.add_argument(
        "--input_file",
        type=str,
        default="data/mimic_careunit_clients.pkl",
        help="Input pickle generated by prepare_mimic_careunit_clients.py",
    )
    parser.add_argument(
        "--output_file",
        type=str,
        default="data/mimic_careunit_clients_tokenized_512.pkl",
        help="Output pickle with input_ids/attention_mask/label per split.",
    )
    parser.add_argument(
        "--stats_file",
        type=str,
        default="data/mimic_careunit_clients_tokenized_512_stats.json",
        help="JSON file storing tokenization metadata.",
    )
    parser.add_argument(
        "--model",
        type=str,
        default="roberta",
        choices=["roberta", "gpt"],
        help="Tokenizer family to use.",
    )
    parser.add_argument(
        "--max_length",
        type=int,
        default=512,
        help="Tokenizer max length.",
    )
    parser.add_argument(
        "--front_tokens",
        type=int,
        default=256,
        help="Number of tokens to keep from the beginning before adding special tokens.",
    )
    parser.add_argument(
        "--back_tokens",
        type=int,
        default=256,
        help="Number of tokens to keep from the end before adding special tokens.",
    )
    return parser.parse_args()


def get_tokenizer(model_name):
    if model_name == "roberta":
        return RobertaTokenizer.from_pretrained(MODEL_FILE)
    if model_name == "gpt":
        tokenizer = GPT2Tokenizer.from_pretrained(MODEL_FILE)
        if tokenizer.pad_token is None:
            tokenizer.pad_token = tokenizer.eos_token
        return tokenizer
    raise ValueError(f"Unsupported model: {model_name}")


def _compute_head_tail_budget(tokenizer, max_length, front_tokens, back_tokens):
    if front_tokens < 0 or back_tokens < 0:
        raise ValueError("front_tokens and back_tokens must be >= 0")

    num_special_tokens = tokenizer.num_special_tokens_to_add(pair=False)
    content_budget = max_length - num_special_tokens
    if content_budget <= 0:
        raise ValueError(
            f"max_length={max_length} is too small after accounting for {num_special_tokens} special tokens."
        )

    if front_tokens + back_tokens <= content_budget:
        return front_tokens, back_tokens, num_special_tokens, content_budget

    # Reserve room for special tokens. With RoBERTa max_length=512 this becomes 255+255.
    scaled_front = int(round(front_tokens * content_budget / (front_tokens + back_tokens)))
    scaled_front = max(0, min(content_budget, scaled_front))
    scaled_back = content_budget - scaled_front
    return scaled_front, scaled_back, num_special_tokens, content_budget


def _encode_head_tail_texts(texts, tokenizer, max_length, front_tokens, back_tokens):
    keep_front, keep_back, num_special_tokens, content_budget = _compute_head_tail_budget(
        tokenizer, max_length, front_tokens, back_tokens
    )

    raw_encoded = tokenizer(
        texts,
        add_special_tokens=False,
        truncation=False,
        padding=False,
    )

    final_input_ids = []
    final_attention_masks = []
    truncated_examples = 0
    original_lengths = []
    effective_lengths = []

    for token_ids in raw_encoded["input_ids"]:
        original_lengths.append(len(token_ids))
        if len(token_ids) > content_budget:
            truncated_examples += 1

        if len(token_ids) <= content_budget:
            kept_ids = token_ids
        else:
            if keep_front == 0:
                kept_ids = token_ids[-keep_back:]
            elif keep_back == 0:
                kept_ids = token_ids[:keep_front]
            else:
                kept_ids = token_ids[:keep_front] + token_ids[-keep_back:]

        prepared = tokenizer.prepare_for_model(
            kept_ids,
            add_special_tokens=True,
            padding="max_length",
            truncation=True,
            max_length=max_length,
            return_attention_mask=True,
        )
        final_input_ids.append(prepared["input_ids"])
        final_attention_masks.append(prepared["attention_mask"])
        effective_lengths.append(int(sum(prepared["attention_mask"])) - num_special_tokens)

    metadata = {
        "requested_front_tokens": front_tokens,
        "requested_back_tokens": back_tokens,
        "effective_front_tokens": keep_front,
        "effective_back_tokens": keep_back,
        "num_special_tokens": num_special_tokens,
        "content_budget": content_budget,
        "truncated_examples": truncated_examples,
        "total_examples": len(texts),
        "avg_original_token_length": (
            float(sum(original_lengths) / len(original_lengths)) if original_lengths else 0.0
        ),
        "max_original_token_length": max(original_lengths) if original_lengths else 0,
        "avg_effective_content_tokens": (
            float(sum(effective_lengths) / len(effective_lengths)) if effective_lengths else 0.0
        ),
    }
    return final_input_ids, final_attention_masks, metadata


def _encode_head_tail_texts_gpu(
        texts,
        tokenizer,
        max_length,
        front_tokens,
        back_tokens,
        device="cuda:0",
        encode_batch_size=128,
):
    """Head-tail tokenization with batched GPU tensor assembly (padding / truncation)."""
    import torch

    keep_front, keep_back, num_special_tokens, content_budget = _compute_head_tail_budget(
        tokenizer, max_length, front_tokens, back_tokens
    )
    dev = torch.device(device if torch.cuda.is_available() else "cpu")
    if dev.type == "cuda":
        print(f"GPU encoding on {dev}: {torch.cuda.get_device_name(dev)}")
    else:
        print("CUDA unavailable, falling back to CPU for tensor assembly.")

    bos_id = tokenizer.bos_token_id
    if bos_id is None:
        bos_id = tokenizer.cls_token_id
    eos_id = tokenizer.eos_token_id
    if eos_id is None:
        eos_id = tokenizer.sep_token_id
    pad_id = tokenizer.pad_token_id

    final_input_ids = []
    final_attention_masks = []
    truncated_examples = 0
    original_lengths = []
    effective_lengths = []

    for start in range(0, len(texts), encode_batch_size):
        batch_texts = texts[start:start + encode_batch_size]
        raw_encoded = tokenizer(
            batch_texts,
            add_special_tokens=False,
            truncation=False,
            padding=False,
        )

        for token_ids in raw_encoded["input_ids"]:
            original_lengths.append(len(token_ids))
            if len(token_ids) > content_budget:
                truncated_examples += 1

            if len(token_ids) <= content_budget:
                kept_ids = token_ids
            elif keep_front == 0:
                kept_ids = token_ids[-keep_back:]
            elif keep_back == 0:
                kept_ids = token_ids[:keep_front]
            else:
                kept_ids = token_ids[:keep_front] + token_ids[-keep_back:]

            seq = torch.tensor([bos_id] + kept_ids + [eos_id], dtype=torch.long, device=dev)
            attn = torch.ones_like(seq)
            cur_len = int(seq.size(0))

            if cur_len > max_length:
                seq = seq[:max_length]
                attn = attn[:max_length]
                seq[-1] = eos_id
                cur_len = max_length

            if cur_len < max_length:
                pad_len = max_length - cur_len
                seq = torch.cat(
                    [seq, torch.full((pad_len,), pad_id, dtype=torch.long, device=dev)]
                )
                attn = torch.cat(
                    [attn, torch.zeros(pad_len, dtype=torch.long, device=dev)]
                )

            effective_lengths.append(int(attn.sum().item()) - num_special_tokens)
            final_input_ids.append(seq.cpu().tolist())
            final_attention_masks.append(attn.cpu().tolist())

        if dev.type == "cuda":
            torch.cuda.empty_cache()

    metadata = {
        "requested_front_tokens": front_tokens,
        "requested_back_tokens": back_tokens,
        "effective_front_tokens": keep_front,
        "effective_back_tokens": keep_back,
        "num_special_tokens": num_special_tokens,
        "content_budget": content_budget,
        "truncated_examples": truncated_examples,
        "total_examples": len(texts),
        "encode_device": str(dev),
        "encode_batch_size": encode_batch_size,
        "avg_original_token_length": (
            float(sum(original_lengths) / len(original_lengths)) if original_lengths else 0.0
        ),
        "max_original_token_length": max(original_lengths) if original_lengths else 0,
        "avg_effective_content_tokens": (
            float(sum(effective_lengths) / len(effective_lengths)) if effective_lengths else 0.0
        ),
    }
    return final_input_ids, final_attention_masks, metadata


def tokenize_split(
        split_dataset,
        tokenizer,
        max_length,
        front_tokens,
        back_tokens,
        device=None,
        encode_batch_size=128,
):
    texts = split_dataset["text"]
    if device is not None and str(device).lower() != "cpu":
        input_ids, attention_masks, split_metadata = _encode_head_tail_texts_gpu(
            texts,
            tokenizer,
            max_length,
            front_tokens,
            back_tokens,
            device=device,
            encode_batch_size=encode_batch_size,
        )
    else:
        input_ids, attention_masks, split_metadata = _encode_head_tail_texts(
            texts, tokenizer, max_length, front_tokens, back_tokens
        )
    return Dataset.from_dict(
        {
            "input_ids": input_ids,
            "attention_mask": attention_masks,
            "label": split_dataset["label"],
        }
    ), split_metadata


def main():
    args = parse_args()
    input_file = Path(args.input_file)
    output_file = Path(args.output_file)
    stats_file = Path(args.stats_file)

    if not input_file.exists():
        raise FileNotFoundError(f"Input file not found: {input_file}")

    tokenizer = get_tokenizer(args.model)

    with input_file.open("rb") as f:
        fed_dataset = pickle.load(f)

    tokenized_dataset = {
        "train": [],
        "vali": [],
        "test": [],
        "client_names": fed_dataset.get("client_names", []),
        "partition_key": fed_dataset.get("partition_key", "FIRST_CAREUNIT"),
        "dropped_clients": fed_dataset.get("dropped_clients", []),
        "tokenized": True,
        "tokenizer_model": args.model,
        "max_length": args.max_length,
        "tokenization_strategy": "head_tail",
    }
    split_tokenization_stats = {split_name: [] for split_name in ["train", "vali", "test"]}

    for split_name in ["train", "vali", "test"]:
        for client_idx, client_split in enumerate(fed_dataset[split_name]):
            tokenized_split, split_metadata = tokenize_split(
                client_split,
                tokenizer,
                args.max_length,
                args.front_tokens,
                args.back_tokens,
            )
            tokenized_dataset[split_name].append(tokenized_split)
            split_tokenization_stats[split_name].append(
                {
                    "client_id": client_idx,
                    "client_name": (
                        tokenized_dataset["client_names"][client_idx]
                        if client_idx < len(tokenized_dataset["client_names"])
                        else f"client_{client_idx}"
                    ),
                    **split_metadata,
                }
            )

    output_file.parent.mkdir(parents=True, exist_ok=True)
    stats_file.parent.mkdir(parents=True, exist_ok=True)

    with output_file.open("wb") as f:
        pickle.dump(tokenized_dataset, f)

    stats = {
        "input_file": str(input_file),
        "output_file": str(output_file),
        "tokenizer_model": args.model,
        "max_length": args.max_length,
        "requested_front_tokens": args.front_tokens,
        "requested_back_tokens": args.back_tokens,
        "n_clients": len(tokenized_dataset["train"]),
        "client_names": tokenized_dataset["client_names"],
        "split_sizes": {
            split_name: [len(ds) for ds in tokenized_dataset[split_name]]
            for split_name in ["train", "vali", "test"]
        },
        "split_tokenization_stats": split_tokenization_stats,
    }
    with stats_file.open("w", encoding="utf-8") as f:
        json.dump(stats, f, ensure_ascii=False, indent=2)

    print(f"Tokenized dataset saved -> {output_file}")
    print(f"Tokenization stats saved -> {stats_file}")
    print(f"n_clients = {stats['n_clients']}")
    print(f"max_length = {args.max_length}")
    print(
        "head-tail tokenization = "
        f"front {stats['split_tokenization_stats']['train'][0]['effective_front_tokens'] if stats['split_tokenization_stats']['train'] else 0} + "
        f"back {stats['split_tokenization_stats']['train'][0]['effective_back_tokens'] if stats['split_tokenization_stats']['train'] else 0}"
    )


if __name__ == "__main__":
    main()
